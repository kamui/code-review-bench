import sys
n, k, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
variants = ",\n".join(f"  z.object({{ kind: z.literal('k{i}'), field{i}: z.string() }})" for i in range(n))
uses = "\n".join("    .use((opts) => opts.next())" for _ in range(k))
open(out, "w").write(f"""// Generated by gen.py: a discriminated union of {n} variants, each with one field of its own,
// followed by {k} middleware(s) that change nothing.
import {{ inferRouterInputs, initTRPC }} from '@trpc/server';
import {{ z }} from 'zod';

const t = initTRPC.create();
const schema = z.discriminatedUnion('kind', [
{variants},
]);
export const router = t.router({{
  proc: t.procedure
    .input(schema)
{uses}
    .query(({{ input }}) => input.kind),
}});
type Input = inferRouterInputs<typeof router>['proc'];
export const first: Input = {{ kind: 'k0', field0: 'x' }};
export type Show_caller = Input;
""")
