#!/bin/sh
# Usage: documented-way.sh <weed binary> <empty work dir> <redis-cli> <cluster node ports, comma-separated>
# The documented way to turn on replica reads for the redis_cluster2 filer store, run end to end:
# generate filer.toml with "weed scaffold -config=filer", switch the default store off, enable
# [redis_cluster2] with the scratch cluster's addresses, set the documented key, start a real
# "weed server -filer" from that directory, store one file over HTTP, read it 20 times over HTTP,
# and count on every Redis node how many GET commands it served. Done four times: the scaffold's
# readOnly = true; useReadOnly = true added; routeByLatency = true; the scaffold unchanged and
# WEED_REDIS_CLUSTER2_READONLY=true in the environment. Also prints what the filer
# logged about its store.
set -u
weed=$1; work=$2; cli=$3; ports=$4
mkdir -p "$work"
cd "$work" || exit 1
"$weed" scaffold -config=filer -output=. >/dev/null 2>&1
cp filer.toml filer.toml.scaffold
addrs=$(echo "$ports" | tr ',' '\n' | sed 's/.*/"127.0.0.1:&"/' | paste -sd, -)
echo "# weed: $("$weed" version 2>/dev/null | head -1)"
echo "# scaffold section as generated by 'weed scaffold -config=filer':"
awk '/^\[redis_cluster2\]/{p=1} p&&/^\[/&&!/^\[redis_cluster2\]/{p=0} p' filer.toml.scaffold | sed 's/^/#   /'
run_case() {
  label=$1; edit=$2; envset=${3:-}
  python3 -I - "$work/filer.toml.scaffold" "$work/filer.toml" "$addrs" "$edit" <<'PY'
import sys
src, dst, addrs, edit = sys.argv[1:5]
text = open(src).read()
# switch off the default store, enable redis_cluster2
text = text.replace("[leveldb2]\n# local on disk, mostly for simple single-machine setup, fairly scalable\n# faster than previous leveldb, recommended.\nenabled = true", "[leveldb2]\n# local on disk, mostly for simple single-machine setup, fairly scalable\n# faster than previous leveldb, recommended.\nenabled = false")
start = text.index("[redis_cluster2]\n")
end = text.index("\n[", start + 1)
section = text[start:end]
lines = section.split("\n")
out, skip = [], False
for line in lines:
    s = line.strip()
    if skip:
        if s == "]":
            skip = False
        continue
    if s.startswith("addresses = ["):
        out.append("addresses = [" + addrs + "]")
        skip = not s.endswith("]")
        continue
    if s == "enabled = false":
        out.append("enabled = true")
        continue
    if edit.startswith("add:") is False and s == edit.split("->")[0].strip():
        out.append(edit.split("->")[1].strip())
        continue
    out.append(line)
if edit.startswith("add:"):
    out.insert(1, edit[4:])
text = text[:start] + "\n".join(out) + text[end:]
assert "enabled = false" in text[text.index("[leveldb2]"):text.index("[leveldb2]") + 200], "leveldb2 not switched off"
open(dst, "w").write(text)
PY
  echo
  echo "## case: $label"
  echo "# [redis_cluster2] as edited:"
  awk '/^\[redis_cluster2\]/{p=1} p&&/^\[/&&!/^\[redis_cluster2\]/{p=0} p' filer.toml | grep -v '^#' | grep -v '^$' | sed 's/^/#   /'
  rm -rf data log.txt; mkdir -p data
  [ -n "$envset" ] && echo "# environment: $envset"
  env $envset "$weed" server -dir=data -ip=127.0.0.1 -master.port=29333 -volume.port=29080 -filer -filer.port=29888 >log.txt 2>&1 &
  pid=$!
  i=0; until curl -s -o /dev/null http://127.0.0.1:29888/ || [ $i -ge 60 ]; do sleep 1; i=$((i+1)); done
  sleep 2
  echo "hello" > f.txt
  curl -s -F file=@f.txt "http://127.0.0.1:29888/p1dir/f.txt" >/dev/null
  sleep 1
  for p in $(echo "$ports" | tr ',' ' '); do "$cli" -p "$p" config resetstat >/dev/null; done
  ok=0; for n in $(seq 1 20); do curl -s -o /dev/null -w '%{http_code}\n' -I "http://127.0.0.1:29888/p1dir/f.txt" | grep -q 200 && ok=$((ok+1)); done
  echo "# 20 HEAD requests for /p1dir/f.txt over HTTP, $ok answered 200"
  for p in $(echo "$ports" | tr ',' ' '); do
    role=$("$cli" -p "$p" role | head -1)
    gets=$("$cli" -p "$p" info commandstats | tr -d '\r' | grep '^cmdstat_get:' | sed 's/cmdstat_get:calls=\([0-9]*\),.*/\1/')
    echo "#   node 127.0.0.1:$p ($role): GET calls ${gets:-0}"
  done
  echo "# what the filer logged about its store (grep -i 'store\|readonly\|redis'):"
  grep -i 'filer store\|configured filer\|readonly\|redis' log.txt | head -5 | sed 's/^/#   /'
  kill "$pid"; wait "$pid" 2>/dev/null
  for p in $(echo "$ports" | tr ',' ' '); do "$cli" -c -p "$p" --scan --pattern '/p1dir*' | while read -r k; do "$cli" -c -p "$p" del "$k" >/dev/null; done; done
  printf '%s\n' 'ZREM "/\x00" p1dir' | "$cli" -c -p "$(echo "$ports" | cut -d, -f1)" >/dev/null
}
run_case "the documented key: readOnly = true" "readOnly = false -> readOnly = true"
run_case "the key the code reads: useReadOnly = true (added)" "add:useReadOnly = true"
run_case "the other documented key: routeByLatency = true" "routeByLatency = false -> routeByLatency = true"
run_case "the documented environment variable WEED_REDIS_CLUSTER2_READONLY=true (wiki Environment-Variables)" "none -> none" "WEED_REDIS_CLUSTER2_READONLY=true"
